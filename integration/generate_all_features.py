"""Integration test: build one .docx exercising every python-docx write feature, then
reopen it and check that each feature reads back as written.

Usage (from the repository root)::

    uv run python integration/generate_all_features.py

Output goes to ``integration/output/all-features.docx`` – open it in Word / LibreOffice for a
visual check; every section is labelled with the feature it shows. To test .docm/.dotx/.dotm
support, save that file from Word in those formats and use ``check_roundtrip.py``.

Exit code is 0 when every read-back check passes, 1 otherwise.

Not covered because python-docx has no write API for it: hyperlinks (read-only),
footnotes/endnotes, fields/TOC, floating images, content controls, numbering definitions
(lists are made with the built-in "List ..." styles instead).
"""

from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path
from typing import Any, Callable

import docx
from docx import Document
from docx.enum.dml import MSO_THEME_COLOR
from docx.enum.section import WD_ORIENTATION, WD_SECTION_START
from docx.enum.style import WD_STYLE_TYPE
from docx.enum.table import (
    WD_CELL_VERTICAL_ALIGNMENT,
    WD_ROW_HEIGHT_RULE,
    WD_TABLE_ALIGNMENT,
    WD_TABLE_DIRECTION,
)
from docx.enum.text import (
    WD_ALIGN_PARAGRAPH,
    WD_BREAK,
    WD_COLOR_INDEX,
    WD_LINE_SPACING,
    WD_TAB_ALIGNMENT,
    WD_TAB_LEADER,
    WD_UNDERLINE,
)
from docx.shared import Cm, Inches, Pt, RGBColor

ROOT = Path(__file__).resolve().parent.parent
TEST_FILES = ROOT / "features" / "steps" / "test_files"
OUT_DIR = Path(__file__).resolve().parent / "output"
OUT_DOCX = OUT_DIR / "all-features.docx"

IMAGES = {
    "png": TEST_FILES / "monty-truth.png",
    "jpeg": TEST_FILES / "python-icon.jpeg",
    "gif": TEST_FILES / "lena.gif",
    "bmp": TEST_FILES / "lena.bmp",
    "tiff": TEST_FILES / "sample.tif",
}

CREATED = dt.datetime(2026, 1, 2, 3, 4, 5)


# ================================================================================================
# build
# ================================================================================================


def build(path: Path) -> None:
    document = Document()

    _core_properties(document)
    document.settings.odd_and_even_pages_header_footer = True
    _styles(document)

    document.add_heading("python-docx – all features", level=0)
    _headings(document)
    _runs_and_fonts(document)
    _paragraph_format(document)
    _breaks_and_inline_content(document)
    _lists(document)
    _pictures(document)
    _tables(document)
    _comments(document)
    _sections_headers_footers(document)

    document.save(str(path))


def _core_properties(document: Any) -> None:
    cp = document.core_properties
    cp.author = "Integration Author"
    cp.category = "Integration"
    cp.comments = "Generated by integration/generate_all_features.py"
    cp.content_status = "Draft"
    cp.created = CREATED
    cp.identifier = "ID-0001"
    cp.keywords = "python-docx, integration, test"
    cp.language = "en-US"
    cp.last_modified_by = "Integration Bot"
    cp.last_printed = CREATED
    cp.modified = CREATED
    cp.revision = 7
    cp.subject = "Every feature in one file"
    cp.title = "python-docx integration document"
    cp.version = "1.0"


def _styles(document: Any) -> None:
    styles = document.styles

    para = styles.add_style("Integration Paragraph", WD_STYLE_TYPE.PARAGRAPH)
    para.base_style = styles["Normal"]
    para.next_paragraph_style = styles["Normal"]
    para.font.name = "Arial"
    para.font.size = Pt(11)
    para.font.color.rgb = RGBColor(0x1F, 0x4E, 0x79)
    para.paragraph_format.space_before = Pt(6)
    para.paragraph_format.left_indent = Cm(0.5)
    para.quick_style = True
    para.priority = 1
    para.hidden = False
    para.unhide_when_used = False
    para.locked = False

    char = styles.add_style("Integration Character", WD_STYLE_TYPE.CHARACTER)
    char.base_style = styles["Default Paragraph Font"]
    char.font.bold = True
    char.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)

    styles.add_style("Integration Table", WD_STYLE_TYPE.TABLE).base_style = styles["Table Grid"]

    styles.add_style("Integration To Delete", WD_STYLE_TYPE.PARAGRAPH).delete()

    latent = styles.latent_styles
    latent.default_priority = 99
    latent.load_count = 300
    ls = latent.add_latent_style("Integration Latent")
    ls.priority = 42
    ls.hidden = True
    ls.unhide_when_used = True
    ls.quick_style = False
    ls.locked = True


def _headings(document: Any) -> None:
    document.add_heading("1. Headings", level=1)
    for level in range(2, 10):
        document.add_heading(f"Heading level {level}", level=level)


def _runs_and_fonts(document: Any) -> None:
    document.add_heading("2. Runs and font properties", level=1)

    p = document.add_paragraph("Plain run, then: ")
    p.add_run("bold").bold = True
    p.add_run(" ")
    p.add_run("italic").italic = True
    p.add_run(" ")
    p.add_run("underline").underline = True
    p.add_run(" ")
    p.add_run("custom character style", style="Integration Character")

    p = document.add_paragraph("Underline types: ")
    for u in (WD_UNDERLINE.DOUBLE, WD_UNDERLINE.WAVY, WD_UNDERLINE.DOTTED, WD_UNDERLINE.THICK):
        r = p.add_run(f"{u.name} ")
        r.underline = u

    bool_props = [
        "all_caps", "small_caps", "strike", "double_strike", "subscript", "superscript",
        "shadow", "outline", "emboss", "imprint", "hidden", "rtl", "no_proof", "snap_to_grid",
        "spec_vanish", "web_hidden", "math", "cs_bold", "cs_italic", "complex_script",
    ]  # fmt: skip
    p = document.add_paragraph("Boolean font properties: ")
    for prop in bool_props:
        r = p.add_run(f"{prop} ")
        setattr(r.font, prop, True)

    p = document.add_paragraph()
    r = p.add_run("Arial 16pt RGB color, yellow highlight")
    r.font.name = "Arial"
    r.font.size = Pt(16)
    r.font.color.rgb = RGBColor(0x00, 0x80, 0x40)
    r.font.highlight_color = WD_COLOR_INDEX.YELLOW
    r = p.add_run(" theme color ACCENT_2")
    r.font.color.theme_color = MSO_THEME_COLOR.ACCENT_2

    p = document.add_paragraph("Old text that is replaced by the text setter")
    p.text = "Paragraph.text setter\twith a tab\nand a line break"
    p.runs[0].text = "Run.text setter\twith a tab\nand a line break"

    p = document.add_paragraph("This paragraph is cleared then refilled.")
    p.clear().add_run("Paragraph.clear() then add_run()")

    p = document.add_paragraph("Before")
    p.insert_paragraph_before("insert_paragraph_before() puts me above 'Before'", style="Quote")

    p = document.add_paragraph(style="Integration Paragraph")
    p.add_run("Paragraph using the custom paragraph style")
    r = p.add_run(" cleared run")
    r.clear().add_text(" (Run.clear() then add_text())")


def _paragraph_format(document: Any) -> None:
    document.add_heading("3. Paragraph formatting", level=1)

    for align in (WD_ALIGN_PARAGRAPH.LEFT, WD_ALIGN_PARAGRAPH.CENTER,
                  WD_ALIGN_PARAGRAPH.RIGHT, WD_ALIGN_PARAGRAPH.JUSTIFY):  # fmt: skip
        document.add_paragraph(f"Alignment {align.name}").alignment = align

    p = document.add_paragraph("Indents: left 1in, right 0.5in, first line -0.25in (hanging)")
    pf = p.paragraph_format
    pf.left_indent = Inches(1)
    pf.right_indent = Inches(0.5)
    pf.first_line_indent = Inches(-0.25)

    p = document.add_paragraph("Spacing: 12pt before, 18pt after, line spacing exactly 20pt")
    pf = p.paragraph_format
    pf.space_before = Pt(12)
    pf.space_after = Pt(18)
    pf.line_spacing = Pt(20)
    pf.line_spacing_rule = WD_LINE_SPACING.EXACTLY

    p = document.add_paragraph("Line spacing 1.5 (multiple), pagination flags all set")
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.keep_together = True
    pf.keep_with_next = True
    pf.widow_control = True

    p = document.add_paragraph("Left\tCenter\tRight dots\tDecimal 3.14")
    tabs = p.paragraph_format.tab_stops
    tabs.add_tab_stop(Inches(2), WD_TAB_ALIGNMENT.CENTER)
    tabs.add_tab_stop(Inches(4), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
    tabs.add_tab_stop(Inches(5.5), WD_TAB_ALIGNMENT.DECIMAL, WD_TAB_LEADER.DASHES)


def _breaks_and_inline_content(document: Any) -> None:
    document.add_heading("4. Breaks", level=1)
    p = document.add_paragraph()
    r = p.add_run("Line break after this")
    r.add_break()  # -- WD_BREAK.LINE --
    r.add_text("tab after this")
    r.add_tab()
    r.add_text("end of run")

    p = document.add_paragraph("Page break inside a run follows")
    p.add_run().add_break(WD_BREAK.PAGE)
    document.add_paragraph("Text after the run page break")
    p = document.add_paragraph("Starts on a new page (page_break_before)")
    p.paragraph_format.page_break_before = True

    document.add_page_break()


def _lists(document: Any) -> None:
    document.add_heading("5. Lists (built-in list styles)", level=1)
    for style in ("List Bullet", "List Bullet 2", "List Number", "List Number 2"):
        document.add_paragraph(f"Item using style '{style}'", style=style)


def _pictures(document: Any) -> None:
    document.add_heading("6. Pictures (one per format)", level=1)
    for fmt, path in IMAGES.items():
        document.add_paragraph(f"{fmt.upper()} image, width 1.5in:")
        document.add_picture(str(path), width=Inches(1.5))
    p = document.add_paragraph("Inline picture inside a run → ")
    p.add_run().add_picture(str(IMAGES["png"]), height=Cm(1))
    shape = document.inline_shapes[0]
    shape.width = Inches(2)  # -- resize first picture after insertion --


def _tables(document: Any) -> None:
    document.add_heading("7. Tables", level=1)

    table = document.add_table(rows=3, cols=3, style="Light Grid Accent 1")
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    for r, row in enumerate(table.rows):
        for c, cell in enumerate(row.cells):
            cell.text = f"r{r}c{c}"
    table.add_row().cells[0].text = "added row"
    table.add_column(Inches(1)).cells[0].text = "added col"

    a = table.cell(1, 0).merge(table.cell(2, 1))  # -- 2x2 merge --
    a.text = "merged 2x2"
    a.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER

    row = table.rows[0]
    row.height = Cm(1.2)
    row.height_rule = WD_ROW_HEIGHT_RULE.EXACTLY
    table.columns[0].width = Inches(1.5)
    table.cell(0, 2).width = Inches(1.2)

    cell = table.cell(0, 1)
    cell.add_paragraph("second paragraph in cell", style="Integration Paragraph")
    nested = cell.add_table(rows=2, cols=2)
    nested.style = "Table Grid"
    nested.cell(0, 0).text = "nested"

    document.add_paragraph()
    rtl = document.add_table(rows=1, cols=2, style="Integration Table")
    rtl.table_direction = WD_TABLE_DIRECTION.RTL
    rtl.cell(0, 0).text = "RTL table, first cell"
    rtl.cell(0, 1).text = "second cell"


def _comments(document: Any) -> None:
    document.add_heading("8. Comments", level=1)
    p = document.add_paragraph("This sentence ")
    run = p.add_run("carries a comment")
    p.add_run(" and this part does not.")
    comment = document.add_comment(run, text="First comment paragraph", author="Reviewer",
                                   initials="RV")  # fmt: skip
    comment.add_paragraph("Second comment paragraph")
    comment.author = "Integration Reviewer"
    comment.initials = "IR"

    p = document.add_paragraph("A comment spanning the whole paragraph, ")
    p.add_run("over several runs.")
    document.add_comment(p.runs, text="Spans all runs", author="Reviewer", initials="RV")


def _sections_headers_footers(document: Any) -> None:
    first = document.sections[0]
    first.different_first_page_header_footer = True
    first.header.paragraphs[0].text = "Primary (odd) header – section 1"
    first.even_page_header.paragraphs[0].text = "Even page header – section 1"
    first.first_page_header.paragraphs[0].text = "First page header – section 1"
    first.footer.paragraphs[0].text = "Primary footer – section 1"
    first.even_page_footer.paragraphs[0].text = "Even page footer – section 1"
    first.first_page_footer.paragraphs[0].text = "First page footer – section 1"
    first.header.add_paragraph().add_run().add_picture(str(IMAGES["png"]), height=Cm(0.8))
    first.footer.add_table(rows=1, cols=2, width=Inches(6)).cell(0, 0).text = "footer table"

    sec = document.add_section(WD_SECTION_START.NEW_PAGE)
    document.add_heading("9. Landscape section with custom margins", level=1)
    sec.orientation = WD_ORIENTATION.LANDSCAPE
    sec.page_width, sec.page_height = sec.page_height, sec.page_width
    sec.top_margin = Cm(2)
    sec.bottom_margin = Cm(2)
    sec.left_margin = Cm(3)
    sec.right_margin = Cm(3)
    sec.gutter = Cm(0.5)
    sec.header_distance = Cm(1)
    sec.footer_distance = Cm(1)
    sec.header.is_linked_to_previous = False
    sec.header.paragraphs[0].text = "Header – section 2 (landscape, unlinked)"

    sec = document.add_section(WD_SECTION_START.CONTINUOUS)
    document.add_heading("10. Continuous section (header linked to previous)", level=1)
    document.add_paragraph("This section's header is inherited from section 2.")

    sec = document.add_section(WD_SECTION_START.ODD_PAGE)
    sec.orientation = WD_ORIENTATION.PORTRAIT
    sec.page_width, sec.page_height = sec.page_height, sec.page_width
    document.add_heading("11. Odd-page section, back to portrait", level=1)
    document.add_paragraph("End of document.")


# ================================================================================================
# verify
# ================================================================================================


class Checker:
    def __init__(self) -> None:
        self.passed = 0
        self.failures: list[str] = []

    def eq(self, name: str, actual: Any, expected: Any) -> None:
        if actual == expected:
            self.passed += 1
        else:
            self.failures.append(f"{name}: expected {expected!r}, got {actual!r}")

    def near(self, name: str, actual: int | None, expected: int, tolerance: int = 635) -> None:
        """Lengths stored in twips (1 twip = 635 EMU) round-trip only to the nearest twip."""
        if actual is not None and abs(actual - expected) <= tolerance:
            self.passed += 1
        else:
            self.failures.append(f"{name}: expected {expected!r} ±{tolerance}, got {actual!r}")

    def true(self, name: str, cond: bool) -> None:
        self.eq(name, bool(cond), True)

    def run(self, name: str, fn: Callable[[], None]) -> None:
        try:
            fn()
        except Exception as e:  # noqa: BLE001 -- report any failure, keep checking
            self.failures.append(f"{name}: raised {type(e).__name__}: {e}")


def verify(path: Path) -> Checker:
    ck = Checker()
    document = Document(str(path))

    def core() -> None:
        cp = document.core_properties
        ck.eq("core.author", cp.author, "Integration Author")
        ck.eq("core.title", cp.title, "python-docx integration document")
        ck.eq("core.revision", cp.revision, 7)
        # -- dates are stored as W3CDTF and read back as timezone-aware UTC --
        ck.eq("core.created", cp.created, CREATED.replace(tzinfo=dt.timezone.utc))
        ck.eq("core.keywords", cp.keywords, "python-docx, integration, test")
        ck.eq("core.language", cp.language, "en-US")

    def settings() -> None:
        ck.eq("settings.odd_even", document.settings.odd_and_even_pages_header_footer, True)

    def styles() -> None:
        s = document.styles
        para = s["Integration Paragraph"]
        ck.eq("style.para.type", para.type, WD_STYLE_TYPE.PARAGRAPH)
        ck.eq("style.para.base", para.base_style.name, "Normal")
        ck.eq("style.para.font", para.font.name, "Arial")
        ck.eq("style.para.priority", para.priority, 1)
        ck.eq("style.char.bold", s["Integration Character"].font.bold, True)
        ck.eq("style.table.type", s["Integration Table"].type, WD_STYLE_TYPE.TABLE)
        ck.true("style.deleted", "Integration To Delete" not in s)
        ls = s.latent_styles["Integration Latent"]
        ck.eq("latent.priority", ls.priority, 42)
        ck.eq("latent.locked", ls.locked, True)
        ck.eq("latent.default_priority", s.latent_styles.default_priority, 99)

    def body() -> None:
        paras = document.paragraphs
        texts = [p.text for p in paras]
        ck.eq("title", paras[0].style.name, "Title")
        for level in range(1, 10):
            ck.true(f"heading {level}", any(p.style.name == f"Heading {level}" for p in paras))

        p = next(p for p in paras if p.text.startswith("Plain run"))
        ck.eq("run.bold", p.runs[1].bold, True)
        ck.eq("run.italic", p.runs[3].italic, True)
        ck.eq("run.underline", p.runs[5].underline, True)
        ck.eq("run.char_style", p.runs[7].style.name, "Integration Character")

        p = next(p for p in paras if p.text.startswith("Underline types"))
        ck.eq("underline.double", p.runs[1].underline, WD_UNDERLINE.DOUBLE)

        p = next(p for p in paras if p.text.startswith("Boolean font"))
        for r in p.runs[1:]:
            prop = r.text.strip()
            ck.eq(f"font.{prop}", getattr(r.font, prop), True)

        p = next(p for p in paras if p.text.startswith("Arial 16pt"))
        f = p.runs[0].font
        ck.eq("font.name", f.name, "Arial")
        ck.eq("font.size", f.size, Pt(16))
        ck.eq("font.rgb", f.color.rgb, RGBColor(0x00, 0x80, 0x40))
        ck.eq("font.highlight", f.highlight_color, WD_COLOR_INDEX.YELLOW)
        ck.eq("font.theme", p.runs[1].font.color.theme_color, MSO_THEME_COLOR.ACCENT_2)

        ck.true("text setter", "Run.text setter\twith a tab\nand a line break" in texts)
        ck.true("paragraph.clear", "Paragraph.clear() then add_run()" in texts)
        i = texts.index("Before")
        ck.eq("insert_before", paras[i - 1].style.name, "Quote")
        ck.true("run.clear", any(t.endswith("(Run.clear() then add_text())") for t in texts))

        for name in ("LEFT", "CENTER", "RIGHT", "JUSTIFY"):
            p = next(p for p in paras if p.text == f"Alignment {name}")
            ck.eq(f"align.{name}", p.alignment, getattr(WD_ALIGN_PARAGRAPH, name))

        pf = next(p for p in paras if p.text.startswith("Indents")).paragraph_format
        ck.eq("indent.left", pf.left_indent, Inches(1))
        ck.eq("indent.first", pf.first_line_indent, Inches(-0.25))
        pf = next(p for p in paras if p.text.startswith("Spacing")).paragraph_format
        ck.eq("space_after", pf.space_after, Pt(18))
        ck.eq("line_spacing_rule", pf.line_spacing_rule, WD_LINE_SPACING.EXACTLY)
        pf = next(p for p in paras if p.text.startswith("Line spacing 1.5")).paragraph_format
        ck.eq("line_spacing", pf.line_spacing, 1.5)
        ck.eq("keep_with_next", pf.keep_with_next, True)
        tabs = next(p for p in paras if p.text.startswith("Left\t")).paragraph_format.tab_stops
        ck.eq("tab_stops.count", len(tabs), 3)
        ck.eq("tab_stop.leader", tabs[1].leader, WD_TAB_LEADER.DOTS)
        pf = next(p for p in paras if p.text.startswith("Starts on a new page")).paragraph_format
        ck.eq("page_break_before", pf.page_break_before, True)

        for style in ("List Bullet", "List Number 2"):
            ck.true(f"list.{style}", any(p.style.name == style for p in paras))

    def pictures() -> None:
        shapes = document.inline_shapes
        ck.eq("inline_shapes.count", len(shapes), len(IMAGES) + 1)
        ck.eq("shape.resized", shapes[0].width, Inches(2))
        types = {p.content_type for p in document.part.package.iter_parts()
                 if p.partname.startswith("/word/media/")}  # fmt: skip
        for ct in ("image/png", "image/jpeg", "image/gif", "image/bmp", "image/tiff"):
            ck.true(f"image.{ct}", ct in types)

    def tables() -> None:
        t = document.tables[0]
        ck.eq("table.style", t.style.name, "Light Grid Accent 1")
        ck.eq("table.alignment", t.alignment, WD_TABLE_ALIGNMENT.CENTER)
        ck.eq("table.size", (len(t.rows), len(t.columns)), (4, 4))
        ck.eq("table.merged", t.cell(2, 1).text, "merged 2x2")
        ck.true("table.merged.same", t.cell(1, 0)._tc is t.cell(2, 1)._tc)
        ck.eq("cell.valign", t.cell(1, 0).vertical_alignment, WD_CELL_VERTICAL_ALIGNMENT.CENTER)
        ck.eq("row.height_rule", t.rows[0].height_rule, WD_ROW_HEIGHT_RULE.EXACTLY)
        ck.eq("nested.text", t.cell(0, 1).tables[0].cell(0, 0).text, "nested")
        ck.eq("rtl", document.tables[1].table_direction, WD_TABLE_DIRECTION.RTL)

    def comments() -> None:
        cs = list(document.comments)
        ck.eq("comments.count", len(cs), 2)
        ck.eq("comment.author", cs[0].author, "Integration Reviewer")
        ck.eq("comment.initials", cs[0].initials, "IR")
        ck.eq("comment.text", cs[0].text, "First comment paragraph\nSecond comment paragraph")

    def sections() -> None:
        secs = document.sections
        ck.eq("sections.count", len(secs), 4)
        s0, s1, s2, s3 = secs
        ck.eq("s0.first_page_hdr", s0.different_first_page_header_footer, True)
        ck.eq("s0.even_hdr", s0.even_page_header.paragraphs[0].text,
              "Even page header – section 1")  # fmt: skip
        ck.eq("s0.footer.table", s0.footer.tables[0].cell(0, 0).text, "footer table")
        ck.eq("s1.orientation", s1.orientation, WD_ORIENTATION.LANDSCAPE)
        ck.true("s1.landscape_dims", s1.page_width > s1.page_height)
        ck.near("s1.left_margin", s1.left_margin, Cm(3))
        ck.near("s1.gutter", s1.gutter, Cm(0.5))
        ck.eq("s1.header.linked", s1.header.is_linked_to_previous, False)
        ck.eq("s2.start", s2.start_type, WD_SECTION_START.CONTINUOUS)
        ck.eq("s2.header.linked", s2.header.is_linked_to_previous, True)
        ck.eq("s3.start", s3.start_type, WD_SECTION_START.ODD_PAGE)
        ck.eq("s3.orientation", s3.orientation, WD_ORIENTATION.PORTRAIT)

    def inner_content() -> None:
        kinds = {type(item).__name__ for item in document.iter_inner_content()}
        ck.eq("iter_inner_content", kinds, {"Paragraph", "Table"})

    for name, fn in [("core", core), ("settings", settings), ("styles", styles),
                     ("body", body), ("pictures", pictures), ("tables", tables),
                     ("comments", comments), ("sections", sections),
                     ("inner_content", inner_content)]:  # fmt: skip
        ck.run(name, fn)
    return ck


def main() -> int:
    OUT_DIR.mkdir(exist_ok=True)
    print(f"python-docx {docx.__version__} from {Path(docx.__file__).parent}")
    build(OUT_DOCX)
    print(f"wrote {OUT_DOCX}")
    ck = verify(OUT_DOCX)

    print(f"{ck.passed} checks passed, {len(ck.failures)} failed")
    for failure in ck.failures:
        print(f"  FAIL {failure}")
    return 1 if ck.failures else 0


if __name__ == "__main__":
    sys.exit(main())
